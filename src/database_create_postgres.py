"""Create the Quake Archive PostgreSQL database from scratch.

-------------------------------------------------------
INSTALL: (I use postgres 14 I believe)

brew install postgresql@18
echo 'export PATH="$(brew --prefix postgresql@18)/bin:$PATH"' >> ~/.zshrc
source ~/.zshrc
brew services start postgresql@18

RUN:

python3 -m pip install "psycopg[binary]"
python3 database_create_postgres.py

-------------------------------------------------------
Uses PGDATABASE (default: quake_archive), PGHOST, PGPORT, PGUSER,
and PGPASSWORD where configured. Safe to rerun; does not delete data.
"""

import os

import psycopg
from psycopg import sql

DATABASE = os.environ.get("PGDATABASE", "quake_archive")

METHODS = [
    (
        "archive.org wayback machine list",
        "Query archive.org to get a list of unique URLs that were archived",
    ),
    (
        "archive.org wayback machine crawl",
        "Download archived files and crawl them for file links",
    ),
    (
        "live site crawl",
        "Download the current version of the site and crawl all links",
    ),
]


def main():
    # CREATE DATABASE must run outside a transaction.
    with psycopg.connect(dbname="postgres", autocommit=True) as conn:
        exists = conn.execute(
            "SELECT 1 FROM pg_database WHERE datname = %s", (DATABASE,)
        ).fetchone()
        if not exists:
            conn.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(DATABASE)))
            print(f"Created database: {DATABASE}")
        else:
            print(f"Database already exists: {DATABASE}")

    with psycopg.connect(dbname=DATABASE) as conn:
        with conn.cursor() as cur:
            cur.execute("CREATE EXTENSION IF NOT EXISTS pgcrypto")
            cur.execute("CREATE EXTENSION IF NOT EXISTS pg_trgm")

            cur.execute("""
                CREATE TABLE IF NOT EXISTS quake_website (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    base_url TEXT NOT NULL UNIQUE,
                    original_url TEXT,
                    date_added TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS processing_method (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    method_name TEXT NOT NULL,
                    description TEXT
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS website_processing_status (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    quake_website_id BIGINT NOT NULL REFERENCES quake_website(id),
                    processing_method_id BIGINT NOT NULL REFERENCES processing_method(id),
                    status TEXT NOT NULL,
                    last_processed TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE (quake_website_id, processing_method_id)
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS file_url (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    file_url TEXT NOT NULL
                )
            """)

            # Hash index handles very long URLs; no UNIQUE constraint on TEXT.
            cur.execute("""
                CREATE UNIQUE INDEX IF NOT EXISTS file_url_sha256_idx
                ON file_url (digest(file_url, 'sha256'))
            """)
            cur.execute("""
                CREATE INDEX IF NOT EXISTS idx_file_url_trgm
                ON file_url USING GIN (file_url gin_trgm_ops)
            """)
            cur.execute("""
                CREATE INDEX IF NOT EXISTS idx_quake_website_base_url_trgm
                ON quake_website USING GIN (base_url gin_trgm_ops)
            """)
            cur.execute("""
                ALTER TABLE file_url
                SET (autovacuum_analyze_scale_factor = 0.01)
            """)

            for name, description in METHODS:
                cur.execute("""
                    INSERT INTO processing_method (method_name, description)
                    SELECT %s, %s
                    WHERE NOT EXISTS (
                        SELECT 1 FROM processing_method WHERE method_name = %s
                    )
                """, (name, description, name))

    print("Database, tables, indexes, and processing methods ready.")


if __name__ == "__main__":
    main()
